import { describe, expect, it } from 'vitest';
import { bahtText } from './bahtText';

describe('bahtText', () => {
  it.each([
    [0, 'ศูนย์บาทถ้วน'],
    [1, 'หนึ่งบาทถ้วน'],
    [11, 'สิบเอ็ดบาทถ้วน'],
    [21, 'ยี่สิบเอ็ดบาทถ้วน'],
    [101, 'หนึ่งร้อยเอ็ดบาทถ้วน'],
    [1250.5, 'หนึ่งพันสองร้อยห้าสิบบาทห้าสิบสตางค์'],
    [0.25, 'ยี่สิบห้าสตางค์'],
    [1000000, 'หนึ่งล้านบาทถ้วน'],
    [1000001, 'หนึ่งล้านเอ็ดบาทถ้วน'],
    [2001000, 'สองล้านหนึ่งพันบาทถ้วน'],
    [11000000, 'สิบเอ็ดล้านบาทถ้วน'],
    [564825, 'ห้าแสนหกหมื่นสี่พันแปดร้อยยี่สิบห้าบาทถ้วน'],
    ['49000.00', 'สี่หมื่นเก้าพันบาทถ้วน'],
  ])('%s → %s', (n, words) => {
    expect(bahtText(n)).toBe(words);
  });
});
